#!/usr/bin/env bash
set -euo pipefail

# Project root directory
ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"

VERSION="$(grep '^version =' "${ROOT}/Cargo.toml" | head -1 | cut -d '"' -f 2)"

ARCH="amd64"
PACKAGE="cloudflare-ddns"

STAGE="${ROOT}/build/package"
OUTPUT="${ROOT}/build/output"

echo "Building ${PACKAGE} ${VERSION}"
echo "Project root: ${ROOT}"

# Compile release binary.
cd "${ROOT}"
cargo build --release --locked

# Reset package staging area.
rm -rf "${STAGE}" "${OUTPUT}"
mkdir -p "${OUTPUT}"

install -d "${STAGE}/DEBIAN"
install -d "${STAGE}/usr/bin"
install -d "${STAGE}/usr/lib/systemd/system"
install -d "${STAGE}/usr/share/doc/${PACKAGE}"

# Install binary.
install -m 755 \
    target/release/cloudflare-ddns \
    "${STAGE}/usr/bin/cloudflare-ddns"

# Install systemd service.
install -m 644 \
    packaging/cloudflare-ddns.service \
    "${STAGE}/usr/lib/systemd/system/cloudflare-ddns.service"

# Ship the sample configuration as documentation. The real files in
# /etc/cloudflare-ddns are generated by postinst from the installer prompts,
# so they are intentionally NOT part of the package payload (and therefore
# are never overwritten on upgrade).
install -m 644 \
    config/config.toml \
    "${STAGE}/usr/share/doc/${PACKAGE}/config.example.toml"

# Package metadata: only control needs build-time values.
sed -e "s/@PACKAGE@/${PACKAGE}/g" \
    -e "s/@VERSION@/${VERSION}/g" \
    -e "s/@ARCH@/${ARCH}/g" \
    packaging/debian/control.in > "${STAGE}/DEBIAN/control"

# debconf questions and maintainer scripts are plain files, copied as-is.
install -m 644 packaging/debian/templates "${STAGE}/DEBIAN/templates"
for script in config postinst prerm postrm; do
    install -m 755 "packaging/debian/${script}" "${STAGE}/DEBIAN/${script}"
done

# Build Debian package.
dpkg-deb --build --root-owner-group \
    "${STAGE}" \
    "${OUTPUT}/${PACKAGE}_${VERSION}_${ARCH}.deb"

echo
echo "Package created:"
echo "${OUTPUT}/${PACKAGE}_${VERSION}_${ARCH}.deb"
